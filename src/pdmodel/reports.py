def load_commentary(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    notes, key = {}, None
    for line in path.read_text().splitlines():
        if line.startswith("## "):
            key = line[3:].strip().lower()
            notes[key] = []
        elif key:
            notes[key].append(line)
    return {k: "\n".join(v).strip() for k, v in notes.items() if "\n".join(v).strip()}


def md(df: pd.DataFrame, formats: dict | None = None, default=F4, index=True) -> str:
    """DataFrame -> markdown table. formats: column -> callable."""
    formats = formats or {}
    d = df.copy()
    for c in d.columns:
        f = formats.get(c)
        if f is None and pd.api.types.is_float_dtype(d[c]):
            f = default
        if f is not None:
            d[c] = d[c].map(lambda v, f=f: "" if pd.isna(v) else f(v))
    if index:
        if d.index.name is None and not isinstance(d.index, pd.MultiIndex):
            d.index.name = ""
        d = d.reset_index()
    head = "| " + " | ".join(map(str, d.columns)) + " |"
    sep = "|" + "---|" * len(d.columns)
    body = ["| " + " | ".join(map(str, r)) + " |" for r in d.itertuples(index=False)]
    return "\n".join([head, sep, *body])


def _note(notes, key):
    return notes.get(key, "")


